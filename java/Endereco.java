public class Endereco {
    private String rua;
    private String bairro;
    private int numero;
    private String cidade;

    public Endereco() {}
    public Endereco(String rua, String bairro, int numero, String cidade) {
        this.rua = rua;
        this.bairro = bairro;
        this.numero = numero;
        this.cidade = cidade;
    }
}
